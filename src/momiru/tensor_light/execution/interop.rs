//! Safe host-only borrowed tensor interoperability, without foreign pointer ownership.
use crate::tensor_light::{Rank, Shape, TensorError, TensorView, ValidRank};

/// Borrow initialized f32 data at compile-time rank R, with checked span.
pub fn borrow_host<'a, const R: usize>(
    source: &'a [f32], shape: Shape<R>
) -> Result<TensorView<'a, R>, TensorError>
where Rank<R>: ValidRank {
    TensorView::new(shape, source)
}

/// Foreign memory/device/dtype is not implicitly trusted by the host API.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InteropError {
    UnverifiedForeignMemory,
    UnsupportedDevice,
    UnsupportedDType,
}
